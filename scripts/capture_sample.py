"""Capture Sample-mode data from a Live run.

Runs the real pipeline (app/research.py) against Snowflake and writes the results that the
no-account example (docs/try/) and the Streamlit app's Sample mode replay:

  data/sample/metrics.json   BANK_QUARTERLY_METRICS as generated by setup_synthetic.sql
  data/sample/banks.json     bank directory with peer groups
  data/sample/notes.json     one clean and one injected-claim note per bank (peers = its peer group)
  data/sample/agent.json     Cortex Agent answers to the suggested questions

Usage (key-pair auth; nothing is collected in a browser):
  SNOWFLAKE_ACCOUNT=... SNOWFLAKE_USER=... SNOWFLAKE_PRIVATE_KEY_PATH=... python scripts/capture_sample.py [--resume]
"""
import json
import os
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "app"))
import research as R  # noqa: E402
from snowflake.snowpark import Session  # noqa: E402

OUT = ROOT / "data" / "sample"
QUARTER = "2026-06-30"
QUESTIONS = [
    "Rank the Regional peer group by return on assets for 2026-06-30",
    "Which bank has the lowest equity to assets ratio in the latest quarter?",
    "How did Kestrova Bank's total deposits change over the last 8 quarters?",
    "Compare average return on equity by peer group for 2026",
]


def session():
    return Session.builder.configs({
        "account": os.environ["SNOWFLAKE_ACCOUNT"], "user": os.environ["SNOWFLAKE_USER"],
        "authenticator": "SNOWFLAKE_JWT", "private_key_file": os.environ["SNOWFLAKE_PRIVATE_KEY_PATH"],
        "role": "SNOWPACK_BANK_RESEARCH_ROLE", "warehouse": "SNOWPACK_BANK_RESEARCH_WH",
        "database": "SNOWPACK_BANK_RESEARCH", "schema": "CORE"}).create()


def dump(name, obj):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(json.dumps(obj, indent=1, default=str) + "\n")


def main():
    resume = "--resume" in sys.argv
    s = session()
    banks = R.bank_directory(s)
    dump("banks.json", banks)
    dump("metrics.json", R.metrics(s))

    notes_path = OUT / "notes.json"
    notes = json.loads(notes_path.read_text()) if resume and notes_path.exists() else []
    done = {(n["subject"], n["injected"]) for n in notes}
    for b in banks:
        peers = [x["BANK_NAME"] for x in banks if x["PEER_GROUP"] == b["PEER_GROUP"] and x["ID_RSSD"] != b["ID_RSSD"]]
        for inject in (False, True):
            if (b["BANK_NAME"], inject) in done:
                continue
            rec = R.run_workflow(s, b["BANK_NAME"], peers, QUARTER, inject=inject)
            print(f'{rec["status"]:13} {rec["claims_checked"]:3} {rec["draft_ms"]:6} {rec["verify_ms"]:6}  '
                  f'{b["BANK_NAME"]} inject={inject}', flush=True)
            notes.append(rec)
            dump("notes.json", notes)

    answers = []
    for q in QUESTIONS:
        a = R.ask_agent(s, q)
        print(f'agent {a["ms"]:6} {q}', flush=True)
        answers.append(a)
    dump("agent.json", answers)


if __name__ == "__main__":
    main()
